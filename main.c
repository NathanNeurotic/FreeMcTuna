//=============================================================
// Recursively deletes a folder and its contents.
// This function was obtained from SP193's FreeMcBoot installer.
// Args:
//   folder: The full path to the folder to be deleted (e.g., "mc0:/OPENTUNA").
// Returns:
//   0 on success.
//  -1 or other non-zero value on failure (e.g., if a file/folder couldn't be deleted).
static int DeleteFolder(const char *folder)
{
	DIR *d = opendir(folder);
	size_t path_len = strlen(folder);
	int r = -1;

	if (d)
	{
		//scr_printf("Detected [%s], deleting...\n",folder);
		struct dirent *p;

		r = 0;
		while (!r && (p = readdir(d)))
		{
			int r2 = -1;
			char *buf;
			size_t len;

			/* Skip the names "." and ".." as we don't want to recurse on them. */
			if (!strcmp(p->d_name, ".") || !strcmp(p->d_name, ".."))
				continue;

			len = path_len + strlen(p->d_name) + 2;
			buf = malloc(len);

			if (buf == NULL) {
				PRINTF("DeleteFolder: malloc failed for path component in %s for %s\n", folder, p->d_name);
				// r2 is already -1, which will be propagated to r, indicating an error.
			} else {
				struct stat statbuf;
				snprintf(buf, len, "%s/%s", folder, p->d_name);
				if (!stat(buf, &statbuf)) { // stat succeeded
					if (S_ISDIR(statbuf.st_mode)) {
						r2 = DeleteFolder(buf);
					} else {
						r2 = unlink(buf);
					}
				} else { // stat failed
					PRINTF("DeleteFolder: stat failed for %s. errno: %d\n", buf, errno);
					// r2 is already -1 (initialized at the start of the loop iteration), error will be propagated.
				}
				free(buf);
			}
			r = r2;
		}
		closedir(d);
	}

	if (!r)
		r = rmdir(folder);

	return r;
}

