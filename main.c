// Waits for a specific controller key press (or any key if 'key' is -1).
// Args:
//   key: The PAD_ อะไร (e.g. PAD_CROSS, PAD_START) to wait for.
//        If -1, waits for any key press.
// Returns:
//   The status of the pad when the specified key (or any key) is pressed.
int wait_key(int key)
{
	while (1) // Loop indefinitely until the key is pressed.
	{
		int new_pad = ReadCombinedPadStatus(); // Read combined status of both pads.
		if (key == -1) { // Wait for any key
			if (new_pad != 0) return new_pad;
		} else { // Wait for specific key
			if (new_pad & key)
				return new_pad;
		}
	}
}

// Main function for the UMCS Installer.
// Handles initialization, UI state machine, installation, and cleanup.
// Args:
//   argc: Argument count (not typically used in PS2 homebrew from MC).
//   argv: Argument vector (not typically used).
int main(int argc, char *argv[])
{
	int fdn, icontype;
	unsigned long int ROM_VERSION = 0x170;
	VMode = NTSC; // Default video mode
	int mcport = 0, state; // mcport: selected memory card slot; state: current state of the application
	int key; // Stores controller input

	// Initialize PS2 hardware and basic services (IOP, SIF, FileIO, MC, PAD)
	InitPS2();

	// Reset Graphics Synthesizer (GS) to a known state
	gs_reset();

	// Attempt to read ROM version from rom0:ROMVER.
	// Default to ROM_VERSION = 0x170 and VMode = NTSC if unable to read.
	// Note: ROM_VERSION and VMode are already initialized to these defaults before this block.
	if ((fdn = open("rom0:ROMVER", O_RDONLY)) > 0) // Successfully opened ROMVER
	{
		char romver[5];
		read(fdn, romver, 4); // Read 4 bytes for version, 5th is region
		close(fdn);           // Close the file

		if (romver[4] == 'E') // Check 5th byte for PAL region marker
			VMode = PAL;
		romver[4] = '\0';     // Null-terminate the version string for strtoul
		ROM_VERSION = strtoul(romver, NULL, 16); // Convert hex string to unsigned long
		PRINTF("Main: Successfully read rom0:ROMVER. ROM_VERSION: %lx, VMode: %s\n", ROM_VERSION, VMode == PAL ? "PAL" : "NTSC");
	} else {
		// Failed to open rom0:ROMVER, use default values
		PRINTF("Main: Failed to open rom0:ROMVER (fdn: %d). Using default ROM_VERSION: %lx and VMode: %s\n", fdn, ROM_VERSION, VMode == PAL ? "PAL" : "NTSC");
	}

	// Initialize Graphics Synthesizer based on VMode (PAL or NTSC)
	if (VMode == PAL)
		gs_init(PAL_640_512_32); // Initialize GS for PAL mode
	else
		gs_init(NTSC_640_448_32); // Initialize GS for NTSC mode

	// Initialize PAD input system
	pad_inited = 1;

	// Determine icon type based on ROM version
	icontype = GetIconType(ROM_VERSION);
	int iz = 0; // Variable to store installation result status

	// Set initial state based on ROM compatibility
	if (icontype != UNSUPPORTED)
		state = STATE_MC0; // Compatible ROM, start with MC0 selection
	else
		state = STATE_UNSUPPORTED; // Incompatible ROM

	// Main application loop - finite state machine for UI and actions
	while (1)
	{
		switch (state)
		{
		case STATE_MC0: // State: Displaying options for Memory Card Slot 0
			mcport = 0; // Set current Memory Card port to 0
			display_bmp(640, 448, INST_SLOT_1); // Show screen for MC slot 1 (user perspective)

			key = wait_key(-1); // Wait for any key press

			// Transitions from STATE_MC0
			if ((key & PAD_CROSS) || (key & PAD_CIRCLE)) // X or O pressed
			{
				state = STATE_INSTALL; // Proceed to installation for MC0
				break;
			}
			if ((key & PAD_SELECT) || (key & PAD_L1)) // Select or L1 pressed
			{
				state = STATE_MC1; // Switch to MC1 selection screen
				break;
			}
			// Any other key (typically Start or other unhandled)
			state = STATE_BROWSER; // Exit to PS2 Browser
			break;

		case STATE_MC1: // State: Displaying options for Memory Card Slot 1
			mcport = 1; // Set current Memory Card port to 1
			display_bmp(640, 448, INST_SLOT_2); // Show screen for MC slot 2 (user perspective)

			key = wait_key(-1); // Wait for any key press

			// Transitions from STATE_MC1
			if ((key & PAD_CROSS) || (key & PAD_CIRCLE)) // X or O pressed
			{
				state = STATE_INSTALL; // Proceed to installation for MC1
				break;
			}
			if ((key & PAD_SELECT) || (key & PAD_L1)) // Select or L1 pressed
			{
				state = STATE_MC0; // Switch to MC0 selection screen
				break;
			}
			// Any other key
			state = STATE_BROWSER; // Exit to PS2 Browser
			break;

		case STATE_UNSUPPORTED: // State: Unsupported ROM version detected
			display_bmp(640, 448, NON_COMPATIBLE); // Show non-compatible screen
			key = wait_key(PAD_START); // Wait for Start key press
			state = STATE_BROWSER; // Exit to PS2 Browser
			break;

		case STATE_INSTALL: // State: Performing installation
			display_bmp(640, 448, wait); // Show wait/installation progress screen
			iz = install(mcport, icontype); // Call install function

			// Transitions from STATE_INSTALL
			if (iz) // If install returned an error code (non-zero)
				state = STATE_ERROR; // Go to error screen
			else
				state = STATE_FINISH; // Go to finish/success screen
			break;

		case STATE_FINISH: // State: Installation finished successfully
			display_bmp(640, 448, complete); // Show completion screen
			key = wait_key(PAD_START); // Wait for Start key press
			state = STATE_BROWSER; // Exit to PS2 Browser
			break;

		case STATE_ERROR: // State: Error occurred during installation
			error_message(iz); // Display specific error message based on 'iz' code
			key = wait_key(PAD_START); // Wait for Start key press
			state = STATE_BROWSER; // Exit to PS2 Browser
			break; // Added break, was missing (though execution flows to BROWSER anyway)

		case STATE_BROWSER: // State: Exit to PS2 Browser
			PS2_browser(); // Execute cleanup and load OSDSYS
			break; // Technically unreachable as PS2_browser doesn't return

		default: // Should not happen
			break;
		}
	}

	// This part of the code is unreachable because the main loop (while(1)) never exits,
	// and all program paths eventually lead to PS2_browser() which loads another ELF.
	return 0;
}
