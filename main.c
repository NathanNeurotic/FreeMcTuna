// Initializes core PS2 systems and loads necessary IOP modules.
// This sets up the environment for the installer to function.
static void InitPS2(void)
{
	Reset_IOP(); // Reset IOP and basic system services.
	SifInitIopHeap(); // Initialize IOP heap for module allocation.
	SifLoadFileInit(); // Initialize SIF services for loading files (modules) to IOP.
	fioInit(); // Initialize File I/O library for EE (Emotion Engine).

	// Apply SBV (Sony Bridge Verifier) patches to enable loading IRX modules
	// from EE memory and to disable prefix checks for paths.
	sbv_patch_enable_lmb(); // Load Module Buffer: Allows loading IRX from memory.
	sbv_patch_disable_prefix_check(); // Disables path prefix checking (e.g. "mc0:/").

	// Load essential IOP modules from embedded data.
	// These modules provide services for SIO2 (controllers, memory cards), PAD, and MC.
	SifExecModuleBuffer(SIO2MAN_irx, size_SIO2MAN_irx, 0, NULL, NULL); // Serial I/O manager
	SifExecModuleBuffer(PADMAN_irx, size_PADMAN_irx, 0, NULL, NULL);  // Pad controller manager
	SifExecModuleBuffer(MCMAN_irx, size_MCMAN_irx, 0, NULL, NULL);    // Memory card manager (low-level)
	SifExecModuleBuffer(MCSERV_irx, size_MCSERV_irx, 0, NULL, NULL);  // Memory card server (high-level)
    sbv_patch_fileio(); // Apply file I/O patches (e.g., for wider compatibility). THANKS fjtrujy

	mcInit(MC_TYPE_MC); // Initialize memory card driver with standard type (MC_TYPE_MC) for potentially broader compatibility.
	PadInitPads(); // Initialize the pad (controller) input system.
}

// Writes an embedded file (from memory) to the specified path on a memory card.
// It only writes the file if it does not already exist at the target location.
// Args:
//   embed_file: Pointer to the embedded file data in memory.
//   embed_size: Size of the embedded file data in bytes.
//   folder:     Target folder name on the memory card (e.g., "OPENTUNA").
//   filename:   Target filename on the memory card (e.g., "icon.icn").
//   mcport:     Memory card port number (0 for mc0:, 1 for mc1:).
// Returns:
//    0: Success (file written or already exists).
//   -1: Failed to open the target file for writing.
//   -2: Failed to write the complete file data.
//   -3: snprintf failed to construct the target path (should not happen with valid inputs).
//   -4: Constructed target path was truncated (MAX_PATH too small for the generated path).
static int write_embed(void *embed_file, const int embed_size, char *folder, char *filename, int mcport)
{
	char target[MAX_PATH];
	int path_len;

	path_len = snprintf(target, MAX_PATH, "mc%d:/%s/%s", mcport, folder, filename);

	if (path_len < 0) {
		// snprintf failed (encoding error or other system issue)
		PRINTF("write_embed: snprintf failed to construct path for mc%d:/%s/%s. Error: %d\n", mcport, folder, filename, path_len);
		return -3; // Path construction failure
	} else if (path_len >= MAX_PATH) {
		// Path was truncated
		PRINTF("write_embed: path truncated for mc%d:/%s/%s. Required: %d, Available: %d\n", mcport, folder, filename, path_len, MAX_PATH);
		return -4; // Path truncation
	}

	if (open(target, O_RDONLY) < 0) //if not exist
	{
		int ret, fd;
		if ((fd = open(target, O_CREAT | O_WRONLY | O_TRUNC)) < 0)
		{
			return -1;
		}
		ret = write(fd, embed_file, embed_size);
		if (ret != embed_size)
		{
			return -2;
		}
		close(fd);
	}

	PRINTF("embed file written: %s\n", target);
	return 0;
}

