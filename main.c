// Enum defining the different states of the installer application.
enum STATE
{
	STATE_MC0,			// Main screen: Memory Card slot 0 selected for installation.
	STATE_MC1,			// Main screen: Memory Card slot 1 selected for installation.
	STATE_INSTALL,		// Installation in progress.
	STATE_FINISH,		// Installation completed successfully.
	STATE_ERROR,		// Error occurred during installation.
	STATE_BROWSER,		// Exiting to PS2 Browser.
	STATE_UNSUPPORTED,	// Console's ROM version is not supported.
};

// Determines the icon type category based on the console's ROMVERSION.
// This helps in selecting the appropriate OpenTuna icon variant for the specific console model.
int GetIconType(unsigned long int ROMVERSION)
{
	int icontype;

	if (ROMVERSION >= 0x190) {
		icontype = SLIMS;
	} else if (ROMVERSION == 0x170) { // Specific check for 0x170 first
		icontype = FAT170;
	} else if (ROMVERSION >= 0x110 && ROMVERSION < 0x190) { // General FATS range
		icontype = FATS;
	} else {
		// This includes PROTOKERNELS (0x100, 0x101) and any other unspecified versions.
		// PROTOKERNELS are intentionally mapped to UNSUPPORTED as per the enum ICN comment.
		icontype = UNSUPPORTED;
	}

	return icontype;
}

