// Enum defining different PS2 console types based on ROM version for icon compatibility.
enum ICN
{
	SLIMS = 0,	  // Slim consoles (ROMVER >= 0x190) and SCPH-5000X with ROMVER 0x190
	FATS,		  // Fat consoles (0x110, 0x120, 0x150, 0x160) excluding 0x170
	FAT170,		  // Specific Fat console model (ROMVER 0x170)
	PROTOKERNELS, // Early prototype kernel ROMs (0x100, 0x101). Defined but not used for icon generation by this installer.
	UNSUPPORTED,  // Any other ROM version not covered above.
};

