// Resets the IOP (Input/Output Processor) and re-initializes RPC (Remote Procedure Call).
// This is a standard procedure to ensure a clean state for IOP modules.
static void Reset_IOP(void)
{
	//parrado (Original comment attributing this specific sequence)
	SifInitRpc(0); // Initialize SIF RPC.
	while (!SifIopReset("", 0)) // Reset IOP. Loop until successful.
	{
	};
	while (!SifIopSync()) // Synchronize with IOP. Loop until successful.
	{
	};
	SifInitRpc(0); // Re-initialize SIF RPC after reset.
}

