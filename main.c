//--------------------------------------------------------------
// Checks if a file exists at the given filepath.
// Args:
//   filepath: The full path to the file (e.g., "mc0:/BOOT/BOOT.ELF").
// Returns:
//   1 if the file exists.
//   0 if the file does not exist or an error occurred.
static int file_exists(char *filepath)
{
	int fdn; // File descriptor

	// Try to open the file in read-only mode.
	fdn = open(filepath, O_RDONLY);
	if (fdn < 0) // If open fails (negative fdn), file likely doesn't exist or is inaccessible.
		return 0;

	// File opened successfully, so it exists. Close it.
	close(fdn);
	return 1;
}

